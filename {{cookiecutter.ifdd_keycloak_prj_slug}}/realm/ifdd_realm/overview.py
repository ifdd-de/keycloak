"""A readable overview of the generated realm, as Markdown.

Written next to the import file so that the realm can be read on one page
and changes show up in a review as table rows rather than as JSON.
Rendered from the finished realm, so it cannot disagree with the file.

The page is MyST Markdown for Sphinx: it starts with the label
ifdd-keycloak-realm-overview, so the full documentation can include it and
link to it. Multi-valued table cells use <br>, which the HTML builder keeps.
"""
from typing import Any

from .builtin import Builtin

DURATIONS = {
    "accessTokenLifespan": "Access token lifespan",
    "accessCodeLifespan": "Authorization code lifespan",
    "ssoSessionIdleTimeout": "SSO session idle timeout",
    "ssoSessionMaxLifespan": "SSO session max lifespan",
    "oauth2DeviceCodeLifespan": "Device code lifespan",
}


def cell(value: Any) -> str:
    if isinstance(value, list):
        return "<br>".join(cell(v) for v in value) if value else "–"
    text = str(value) if value not in ("", None) else "–"
    return text.replace("|", "\\|")


def table(header: list[str], rows: list[list[Any]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return lines + [""]


def duration(seconds: int) -> str:
    for unit, size in (("d", 86400), ("h", 3600), ("min", 60)):
        if seconds % size == 0 and seconds >= size:
            return f"{seconds} s ({seconds // size} {unit})"
    return f"{seconds} s"


def flows(client: dict[str, Any]) -> list[str]:
    pkce = client.get("attributes", {}).get("pkce.code.challenge.method")
    code = "authorization code" + (f" (PKCE {pkce})" if pkce else "")
    names = [("standardFlowEnabled", code), ("implicitFlowEnabled", "implicit"),
             ("directAccessGrantsEnabled", "password"), ("serviceAccountsEnabled", "client credentials")]
    return [label for key, label in names if client.get(key)]


def grants(realm_roles: list[str], client_roles: dict[str, list[str]]) -> list[str]:
    items = [f"`{r}`" for r in realm_roles]
    items += [f"`{r}` of `{c}`" for c, rs in client_roles.items() for r in rs]
    return items


def mapper_summary(mapper: dict[str, Any]) -> str:
    config = mapper["config"]
    if mapper["protocolMapper"] == "oidc-audience-mapper":
        values = [config[k] for k in ("included.client.audience", "included.custom.audience") if k in config]
        return "aud += " + ", ".join(values)
    if mapper["protocolMapper"] == "oidc-usermodel-client-role-mapper":
        where = [t for t, k in (("ID token", "id.token.claim"), ("userinfo", "userinfo.token.claim"),
                                ("access token", "access.token.claim")) if config.get(k) == "true"]
        return f"client roles of `{config['usermodel.clientRoleMapping.clientId']}` in " + ", ".join(where)
    if mapper["protocolMapper"] == "oidc-group-membership-mapper":
        return f"claim {config['claim.name']}: group names"
    return f"{mapper['name']} ({mapper['protocolMapper']})"


def render(realm: dict[str, Any], builtin: Builtin, values_file: str = "realm/values.toml") -> str:
    name = realm["realm"]
    own_scopes = [s for s in realm["clientScopes"] if s["name"] not in builtin.names]
    builtin_defaults = set(builtin.default_scopes) | set(builtin.optional_scopes)
    default_role = next(r for r in realm["roles"]["realm"] if r["name"] == realm["defaultRole"]["name"])
    composites = default_role.get("composites", {})

    out = ["(ifdd-keycloak-realm-overview)=", f"# Realm `{name}`", "",
           f"Generated by `realm/build_realm.py` from `{values_file}`; do not edit.",
           f"Import file: `realm/import/{name}-realm.json` (read by Keycloak on its first start only).", ""]

    out += ["## Settings", ""]
    rows = [[DURATIONS[k], duration(realm[k])] for k in DURATIONS if k in realm]
    rows += [["Display name", realm.get("displayName", "none").replace("|", "\\|")],
             ["Login theme", f"`{realm['loginTheme']}`" if realm.get("loginTheme") else "Keycloak default"],
             ["Login with email", "yes" if realm["loginWithEmailAllowed"] else "no"],
             ["SSL required", realm["sslRequired"]],
             ["Refresh token rotation", "yes (each refresh token valid once)"
              if realm.get("revokeRefreshToken") else "no"],
             ["Brute force protection", "yes (Keycloak's thresholds)"
              if realm.get("bruteForceProtected") else "no"],
             ["Password policy", f"`{realm['passwordPolicy']}`" if realm.get("passwordPolicy") else "none"],
             ["Login events", f"kept {duration(realm['eventsExpiration'])}"
              if realm.get("eventsEnabled") else "off"],
             ["Admin events", ("on, without representations" if not realm.get("adminEventsDetailsEnabled")
                               else "on, with representations") if realm.get("adminEventsEnabled") else "off"]]
    out += table(["Setting", "Value"], rows)

    out += ["## Roles", "", "Realm roles:", ""]
    out += table(["Role", "Meaning"],
                 [[f"`{r['name']}`", r["description"]] for r in realm["roles"]["realm"]
                  if r["name"] != default_role["name"]])
    granted = grants(composites.get("realm", []), composites.get("client", {}))
    out += [f"Every user and service account gets the default role `{default_role['name']}`: "
            + ", ".join(granted) + ". Further rights come from groups. Keycloak adds "
            "`offline_access`, `uma_authorization` and the account roles `view-profile`, "
            "`manage-account` on import; no client offers offline tokens.", ""]
    client_roles = [[f"`{c}`", [f"`{r['name']}`" for r in rs]] for c, rs in realm["roles"]["client"].items()]
    if client_roles:
        out += ["Client roles (checked in `resource_access` by ifdd-be and ifdd-ui, "
                "and by ifdd-ts-api for its client):", ""]
        out += table(["Client", "Roles"], client_roles)

    out += ["## Groups", ""]
    out += table(["Group", "Grants"],
                 [[f"`{g['name']}`", grants(g.get("realmRoles", []), g.get("clientRoles", {}))
                   or "membership only (claim `groups`)"] for g in realm["groups"]])

    out += ["## Client scopes", ""]
    realm_defaults = set(realm["defaultDefaultClientScopes"])
    out += table(["Scope", "Default for new clients", "Mappers"],
                 [[f"`{s['name']}`", "yes" if s["name"] in realm_defaults else "no",
                   [mapper_summary(m) for m in s.get("protocolMappers", [])]] for s in own_scopes])
    offered = set(realm["defaultOptionalClientScopes"])
    out += [f"Plus the {len(builtin.client_scopes)} built-in scopes of Keycloak "
            f"(`ifdd_realm/builtin/`), defaults: " + ", ".join(f"`{s}`" for s in builtin.default_scopes)
            + "; optional: " + ", ".join(f"`{s}`" for s in builtin.optional_scopes if s in offered)
            + "; not offered to any client: "
            + (", ".join(f"`{s}`" for s in builtin.optional_scopes if s not in offered) or "–") + ".", ""]

    out += ["## Clients", ""]
    rows = []
    for c in realm["clients"]:
        kind = "public" if c["publicClient"] else f"confidential, secret `{c['secret'][2:-1]}`"
        extra = [s for s in c["defaultClientScopes"] if s not in builtin_defaults]
        rows.append([f"`{c['clientId']}`", c.get("name", ""), kind, flows(c), c["redirectUris"],
                     [f"`{s}`" for s in extra],
                     [mapper_summary(m) for m in c.get("protocolMappers", [])],
                     "yes" if c["fullScopeAllowed"] else "no"])
    out += table(["Client", "Name", "Type", "Flows", "Redirect URIs", "Extra scopes", "Mappers",
                  "Full scope"], rows)
    scoped: dict[str, tuple[list[str], dict[str, list[str]]]] = {}
    for m in realm.get("scopeMappings", []):
        scoped.setdefault(m["client"], ([], {}))[0].extend(m["roles"])
    for owner, mappings in realm.get("clientScopeMappings", {}).items():
        for m in mappings:
            scoped.setdefault(m["client"], ([], {}))[1][owner] = m["roles"]
    if scoped:
        out += [("Roles allowed into the tokens of clients without full scope (besides their own "
                 "client roles):"), ""]
        out += table(["Client", "Roles"], [[f"`{c}`", grants(*rs)] for c, rs in scoped.items()])

    out += ["## Service accounts", ""]
    out += table(["Client", "Roles"],
                 [[f"`{u['serviceAccountClientId']}`", grants(u["realmRoles"], u.get("clientRoles", {}))]
                  for u in realm["users"]])
    out += ["No personal users: create them in the admin console and put them into a group.", ""]
    return "\n".join(out).rstrip() + "\n"
